-- Native clients (SP Music for macOS): incremental library sync, device linking, listening history.
-- Nothing here changes what the web player reads or writes.

-- ── Incremental sync ─────────────────────────────────────────────────────────────────────────────────
-- Every library row carries a revision taken from one sequence. A client remembers the highest revision it
-- has applied and asks for what is above it; deletions are kept as tombstones.
--
-- Writers are serialised by a transaction-level advisory lock taken BEFORE the revision is drawn, so revisions
-- commit in increasing order: a reader's snapshot can never contain revision N+1 while N is still uncommitted.
CREATE SEQUENCE library_rev;

ALTER TABLE artists ADD COLUMN rev bigint NOT NULL DEFAULT nextval('library_rev');
ALTER TABLE albums  ADD COLUMN rev bigint NOT NULL DEFAULT nextval('library_rev');
ALTER TABLE tracks  ADD COLUMN rev bigint NOT NULL DEFAULT nextval('library_rev');
CREATE INDEX artists_rev ON artists (rev);
CREATE INDEX albums_rev  ON albums (rev);
CREATE INDEX tracks_rev  ON tracks (rev);

CREATE TABLE library_tombstones (
  kind       text NOT NULL CHECK (kind IN ('artist', 'album', 'track')),
  id         uuid NOT NULL,
  rev        bigint NOT NULL,
  deleted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (kind, id)
);
CREATE INDEX library_tombstones_rev ON library_tombstones (rev);

CREATE FUNCTION library_next_rev() RETURNS bigint LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(7741001);
  RETURN nextval('library_rev');
END $$;

CREATE FUNCTION library_bump() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.rev := library_next_rev();
  RETURN NEW;
END $$;

CREATE FUNCTION library_tombstone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO library_tombstones (kind, id, rev) VALUES (TG_ARGV[0], OLD.id, library_next_rev())
  ON CONFLICT (kind, id) DO UPDATE SET rev = EXCLUDED.rev, deleted_at = now();
  RETURN OLD;
END $$;

-- A change to a track's files or lyrics is a change to the track as a client sees it.
CREATE FUNCTION library_touch_track() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tid uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN tid := OLD.track_id; ELSE tid := NEW.track_id; END IF;
  IF tid IS NOT NULL THEN UPDATE tracks SET rev = rev WHERE id = tid; END IF;   -- library_bump assigns the new revision
  RETURN NULL;
END $$;

CREATE TRIGGER artists_rev BEFORE INSERT OR UPDATE ON artists FOR EACH ROW EXECUTE FUNCTION library_bump();
CREATE TRIGGER albums_rev  BEFORE INSERT OR UPDATE ON albums  FOR EACH ROW EXECUTE FUNCTION library_bump();
CREATE TRIGGER tracks_rev  BEFORE INSERT OR UPDATE ON tracks  FOR EACH ROW EXECUTE FUNCTION library_bump();
CREATE TRIGGER artists_gone AFTER DELETE ON artists FOR EACH ROW EXECUTE FUNCTION library_tombstone('artist');
CREATE TRIGGER albums_gone  AFTER DELETE ON albums  FOR EACH ROW EXECUTE FUNCTION library_tombstone('album');
CREATE TRIGGER tracks_gone  AFTER DELETE ON tracks  FOR EACH ROW EXECUTE FUNCTION library_tombstone('track');
CREATE TRIGGER media_assets_touch AFTER INSERT OR UPDATE OR DELETE ON media_assets FOR EACH ROW EXECUTE FUNCTION library_touch_track();
CREATE TRIGGER lyrics_touch AFTER INSERT OR UPDATE OR DELETE ON lyrics FOR EACH ROW EXECUTE FUNCTION library_touch_track();

-- ── Device linking ───────────────────────────────────────────────────────────────────────────────────
-- A native app shows a short code; a signed-in browser approves it; the app then receives its own session.
-- Only hashes of the device secret are stored. Rows are short-lived (10 minutes) and single-use.
CREATE TABLE device_links (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_hash  text NOT NULL UNIQUE,
  user_code    text NOT NULL UNIQUE,
  device_name  text NOT NULL DEFAULT '',
  ip           text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL,
  approved_by  uuid REFERENCES users(id) ON DELETE CASCADE,
  decided_at   timestamptz,
  denied       boolean NOT NULL DEFAULT false,
  consumed_at  timestamptz
);

-- ── Listening history ────────────────────────────────────────────────────────────────────────────────
-- The id is generated by the client, so an event sent twice (retry after a lost answer) is stored once.
CREATE TABLE play_events (
  id          uuid PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  track_id    uuid NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
  played_at   timestamptz NOT NULL,
  listened_ms integer NOT NULL DEFAULT 0 CHECK (listened_ms >= 0),
  completed   boolean NOT NULL DEFAULT false,
  source      text NOT NULL DEFAULT 'stream' CHECK (source IN ('stream', 'local')),
  client      text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX play_events_user ON play_events (user_id, played_at DESC);
